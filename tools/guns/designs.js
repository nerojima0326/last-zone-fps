// 좌표: 총 공간 (m), 원점 = 방아쇠, 총구 -Z, 위 +Y, 오른쪽 +X
// 부품: body(고정) · mag(탄창) · slide(슬라이드) · charge(장전 손잡이) · bolt · barrel(중절식) · cyl(실린더) · rearsight(조준경 달면 숨김)
